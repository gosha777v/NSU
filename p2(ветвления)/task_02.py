# Дополнительная версия: re ещё не было в семинаре.
import re

name = input("Имя персонажа: ")
# fullmatch проверяет всю строку; | разделяет варианты.
# IGNORECASE разрешает любой регистр, например дЖеЙмС бОнД.
if re.fullmatch("Джеймс Бонд|Бонд|агент 007|007", name, re.IGNORECASE):
    print("Верно")
else:
    print("Неверно")
