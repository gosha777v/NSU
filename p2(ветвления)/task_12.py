# Попугай, попугая, попугаев
n = int(input("Количество от 1 до 100: "))
if n < 1 or n > 100:
    print("Число должно быть от 1 до 100")
elif 11 <= n % 100 <= 14:
    print(n, "попугаев")
elif n % 10 == 1:
    print(n, "попугай")
elif 2 <= n % 10 <= 4:
    print(n, "попугая")
else:
    print(n, "попугаев")
