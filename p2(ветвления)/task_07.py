# Четырёхзначный палиндром
n = int(input("Четырёхзначное число: "))
if n < 1000 or n > 9999:
    print("Нужно четырёхзначное положительное число")
else:
    a = n // 1000
    b = n // 100 % 10
    c = n // 10 % 10
    d = n % 10
    if a == d and b == c:
        print("настоящее")
    else:
        print("кривое")
